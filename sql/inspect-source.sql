-- What the source schema has, beyond the data.
SELECT TABLE_NAME, COUNT(DISTINCT INDEX_NAME) AS indexes
  FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = 'ubuntu_retail' GROUP BY TABLE_NAME ORDER BY 1;
SELECT COUNT(*) AS foreign_keys FROM information_schema.TABLE_CONSTRAINTS
 WHERE CONSTRAINT_SCHEMA = 'ubuntu_retail' AND CONSTRAINT_TYPE = 'FOREIGN KEY';
SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, COLUMN_DEFAULT, EXTRA
  FROM information_schema.COLUMNS
 WHERE TABLE_SCHEMA = 'ubuntu_retail' AND TABLE_NAME = 'orders' ORDER BY ORDINAL_POSITION;
